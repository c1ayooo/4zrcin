// The vendored copy renames the descriptor file paths inside the rawDesc block
// (the embedding coexistence rename, docs/04 M1) while leaving every other
// descriptor byte — proto packages, field numbers, go_package metadata —
// verbatim. Imports outside the constant are rewritten as documented. Synthetic
// input, no harness checkout needed.
func TestVendoredContentPreservesRawDesc(t *testing.T) {
	const chunk1 = `"\n\x1cprotocol.proto\x12\x03aop\""`
	const chunk2 = `"\xb0\x01B$Z\"github.com/chainreactors/cyber/aop\"b\x06proto3"`
	harness := strings.Join([]string{
		"// Code generated by protoc-gen-go. DO NOT EDIT.",
		"package aop",
		"",
		"const file_aop_protocol_proto_rawDesc = \"\" +",
		"\t" + chunk1 + " +",
		"\t" + chunk2,
		"",
		"var file_aop_protocol_proto_goTypes = []any{",
		"}",
		"",
		"import (",
		"\t\"github.com/chainreactors/cyber/aop/operation\"",
		")",
	}, "\n") + "\n"

	file := AOPProtoFile{
		Name:         "aop/protocol",
		HarnessPath:  "aop/protocol.pb.go",
		VendoredPath: "internal/aop/pb/protocol.pb.go",
		Rewrites:     aopProtoImportRewrites,
	}
	vendored := string(AOPProtoVendoredContent([]byte(harness), file))

	// The descriptor chunks survive untouched: the file name in this sample is
	// "protocol.proto" with no "aop/" prefix, so the coexistence rename does
	// not apply to it, and the go_package inside the descriptor is wire-inert
	// metadata, not an import.
	if !strings.Contains(vendored, chunk1) || !strings.Contains(vendored, chunk2) {
		t.Fatalf("rawDesc chunks were rewritten:\n%s", vendored)
	}
	// The import is rewritten to the vendored layout.
	if !strings.Contains(vendored, `"github.com/c1ayooo/4zrcin/internal/aop/operation"`) {
		t.Fatalf("import not rewritten:\n%s", vendored)
	}
	if strings.Contains(vendored, "github.com/chainreactors/cyber/aop/operation") {
		t.Fatalf("harness import survived:\n%s", vendored)
	}
	// Reassembly is lossless apart from the documented rewrites.
	if _, _, _, found := splitRawDescBlock(strings.ReplaceAll(harness, "\r\n", "\n")); !found {
		t.Fatal("rawDesc block not located in harness input")
	}
}

// A file whose continuation detection would splice mid-chunk must never
// produce output that differs from the harness input outside the documented
// rewrites: pre + block + post always reassemble byte-identically.
func TestSplitRawDescBlockReassembles(t *testing.T) {
	text := "package aop\n\nconst file_x_rawDesc = \"\" +\n\t\"abc\" +\n\t\"def\"\n\nvar y = 1\n"
	pre, block, post, found := splitRawDescBlock(text)
	if !found {
		t.Fatal("block not found")
	}
	if got := pre + block + post; got != text {
		t.Fatalf("reassembly changed the file:\n%q\nwant %q", got, text)
	}
	if !strings.Contains(block, `"def"`) {
		t.Fatalf("block ended before the last chunk: %q", block)
	}
	if !strings.Contains(post, "var y = 1") {
		t.Fatalf("post lost content: %q", post)
	}
}

// The coexistence rename: an aop/-prefixed descriptor path gains the vendored
// namespace and its length prefix is recomputed; the proto package field after
// it stays verbatim (wire type URLs are package-name based, not path based).
func TestVendoredContentRenamesRawDescPaths(t *testing.T) {
	// \n = field 1 (name), \x1c = len 28 = len("aop/operation/protocol.proto");
	// \x12 = field 2 (dependency), \x1a = len 26 ("google/protobuf/...").
	const chunk1 = `"\n\x1caop/operation/protocol.proto\x12\x03aop\""`
	const chunk2 = `"\x12\x1agoogle/protobuf/timestamp.protoB\x06proto3"`
	harness := strings.Join([]string{
		"// Code generated by protoc-gen-go. DO NOT EDIT.",
		"package operation",
		"",
		"const file_aop_operation_protocol_proto_rawDesc = \"\" +",
		"\t" + chunk1 + " +",
		"\t" + chunk2,
		"",
		"var file_aop_operation_protocol_proto_goTypes = []any{",
		"}",
	}, "\n") + "\n"
	file := AOPProtoFile{Name: "aop/operation", HarnessPath: "aop/operation/protocol.pb.go", VendoredPath: "internal/aop/operation/protocol.pb.go"}
	vendored := string(AOPProtoVendoredContent([]byte(harness), file))

	// The file name is renamed and its length prefix grows by len("4zrcin/") = 7:
	// 28 (0x1c) -> 35 (0x23).
	wantName := `"\n\x234zrcin/aop/operation/protocol.proto\x12\x03aop\"`
	if !strings.Contains(vendored, wantName) {
		t.Fatalf("descriptor name not renamed (len prefix must become 0x23):\n%s", vendored)
	}
	// The dependency outside the vendored namespace is untouched.
	if !strings.Contains(vendored, `"\x12\x1agoogle/protobuf/timestamp.proto`) {
		t.Fatalf("dependency mangled:\n%s", vendored)
	}
	// Idempotent: the renamed paths do not match the aop/ pattern again.
	if again := string(AOPProtoVendoredContent([]byte(vendored), file)); again != vendored {
		t.Fatalf("rename is not idempotent:\n%s", again)
	}
}
